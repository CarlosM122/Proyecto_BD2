SELECT table_name, constraint_type, COUNT(*) AS cantidad
  FROM user_constraints
 WHERE table_name IN ('MUNICIPIO','TIPO_ALOJAMIENTO','ALOJAMIENTO','HABITACION',
                      'TEMPORADA','TARIFA','CLIENTE','RESERVA','RESERVA_HABITACION',
