SET DEFINE OFF

/* -----------------------------------------------------------------------------
   0. GUARDA DE SEGURIDAD Y LIMPIEZA (permite re-ejecutar el script)
   a) Guarda: el script se detiene si se ejecuta como SYS o SYSTEM, para no
      crear ni borrar tablas (CLIENTE, RESERVA...) en un esquema administrativo.
      Debe ejecutarse conectado como el usuario dueño del proyecto.
   b) Limpieza: borra las 14 tablas si existen. En una base limpia no hace nada.
   ----------------------------------------------------------------------------- */
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') IN ('SYS','SYSTEM') THEN
    RAISE_APPLICATION_ERROR(-20001,
      'Conectese como el usuario del proyecto (no SYS/SYSTEM) y ejecute de nuevo.');
  END IF;
END;
/
WHENEVER SQLERROR CONTINUE

BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('RESENA','RESERVA_SERVICIO','SERVICIO','PAGO',
                                  'RESERVA_HABITACION','RESERVA','USUARIO_SISTEMA',
                                  'CLIENTE','TARIFA','TEMPORADA','HABITACION',
                                  'ALOJAMIENTO','TIPO_ALOJAMIENTO','MUNICIPIO'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

/* =============================================================================
   1. CATÁLOGOS GEOGRÁFICOS Y DE CLASIFICACIÓN
   ============================================================================= */

/* -----------------------------------------------------------------------------
   MUNICIPIO
   Los 12 municipios del Quindío. Un alojamiento pertenece a exactamente uno.
   UNIQUE(nombre): no puede haber dos municipios con el mismo nombre.
   ----------------------------------------------------------------------------- */
CREATE TABLE municipio (
  id_municipio  NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(60 CHAR)   NOT NULL,
  CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
  CONSTRAINT uq_municipio_nombre UNIQUE (nombre)
);

/* -----------------------------------------------------------------------------
   TIPO_ALOJAMIENTO
   Catálogo extensible: finca cafetera, hotel, glamping, hostal y los que el
   grupo pueda sustentar. Es tabla (y no un CHECK) porque la lista crece.
   ----------------------------------------------------------------------------- */
CREATE TABLE tipo_alojamiento (
  id_tipo      NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre       VARCHAR2(50 CHAR)    NOT NULL,
  descripcion  VARCHAR2(300 CHAR),                       -- opcional
  CONSTRAINT pk_tipo_alojamiento  PRIMARY KEY (id_tipo),
  CONSTRAINT uq_tipo_aloj_nombre  UNIQUE (nombre)
);

/* =============================================================================
   2. OFERTA: ALOJAMIENTOS Y HABITACIONES
   ============================================================================= */

/* -----------------------------------------------------------------------------
   ALOJAMIENTO
   Establecimiento turístico (finca, hotel, glamping, hostal...).
   - estrellas: se las autoasigna el propio alojamiento (1 a 5); no es una
     calificación de clientes (esa sale de RESENA).
   - UNIQUE(id_municipio, nombre_comercial): un mismo nombre comercial no se
     repite dentro del mismo municipio.
   ----------------------------------------------------------------------------- */
CREATE TABLE alojamiento (
  id_alojamiento    NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_municipio      NUMBER(10)          NOT NULL,
  id_tipo           NUMBER(10)          NOT NULL,
  nombre_comercial  VARCHAR2(120 CHAR)  NOT NULL,
  direccion         VARCHAR2(200 CHAR)  NOT NULL,
  estrellas         NUMBER(1)           NOT NULL,
  telefono          VARCHAR2(20)        NOT NULL,
  correo            VARCHAR2(120)       NOT NULL,
  CONSTRAINT pk_alojamiento        PRIMARY KEY (id_alojamiento),
  CONSTRAINT fk_aloj_municipio     FOREIGN KEY (id_municipio) REFERENCES municipio (id_municipio),
  CONSTRAINT fk_aloj_tipo          FOREIGN KEY (id_tipo)      REFERENCES tipo_alojamiento (id_tipo),
  CONSTRAINT uq_aloj_nombre_mpio   UNIQUE (id_municipio, nombre_comercial),
  CONSTRAINT ck_aloj_estrellas     CHECK (estrellas BETWEEN 1 AND 5),
  CONSTRAINT ck_aloj_telefono      CHECK (REGEXP_LIKE(telefono, '^[0-9 +().-]{7,20}$')),
  CONSTRAINT ck_aloj_correo        CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

/* -----------------------------------------------------------------------------
   HABITACION
   Unidad que se reserva (habitación, suite, cabaña...). Cada alojamiento tiene
   un número distinto de ellas (asimetría: 3 en una finca, 40 en un hotel).
   - numero es VARCHAR2 porque puede ser '101', 'C-2', etc.
   - UNIQUE(id_alojamiento, numero): dos habitaciones del mismo alojamiento
     no pueden compartir número (regla 1.1 del enunciado).
   - UNIQUE(id_habitacion, id_alojamiento): es redundante con la PK a
     propósito; sirve de destino para la FK compuesta de RESERVA_HABITACION,
     que así garantiza que la habitación pertenece al alojamiento de la reserva.
   ----------------------------------------------------------------------------- */
CREATE TABLE habitacion (
  id_habitacion   NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento  NUMBER(10)          NOT NULL,
  numero          VARCHAR2(10 CHAR)   NOT NULL,
  capacidad       NUMBER(2)           NOT NULL,
  tipo            VARCHAR2(10)        NOT NULL,
  descripcion     VARCHAR2(500 CHAR),                    -- opcional
  CONSTRAINT pk_habitacion          PRIMARY KEY (id_habitacion),
  CONSTRAINT fk_hab_alojamiento     FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_hab_aloj_numero     UNIQUE (id_alojamiento, numero),
  CONSTRAINT uq_hab_id_aloj         UNIQUE (id_habitacion, id_alojamiento),
  CONSTRAINT ck_hab_capacidad       CHECK (capacidad BETWEEN 1 AND 20),
  CONSTRAINT ck_hab_tipo            CHECK (tipo IN ('SENCILLA','DOBLE','SUITE','CABANA'))
);

/* =============================================================================
   3. TEMPORADAS Y TARIFAS
   ============================================================================= */

/* -----------------------------------------------------------------------------
   TEMPORADA
   Rango de fechas definido por el departamento, con nivel ALTA/MEDIA/BAJA.
   Se define por año: 'Semana Santa' 2025 y 2026 son dos filas distintas.
   - anio = año de fecha_inicio (una temporada dic-ene se registra con el año
     en que empieza).
   - Fechas inclusivas, sin hora (se valida con TRUNC).
   - LIMITACIÓN: que dos temporadas no se traslapen no se puede declarar con un
     CHECK (compara filas distintas). Debe garantizarlo la carga de datos o un
     disparador; es indispensable para que fn_valor_estadia asigne a cada noche
     una sola temporada.
   ----------------------------------------------------------------------------- */
CREATE TABLE temporada (
  id_temporada  NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(60 CHAR)   NOT NULL,
  nivel         VARCHAR2(5)         NOT NULL,
  anio          NUMBER(4)           NOT NULL,
  fecha_inicio  DATE                NOT NULL,
  fecha_fin     DATE                NOT NULL,
  CONSTRAINT pk_temporada         PRIMARY KEY (id_temporada),
  CONSTRAINT uq_temp_nombre_anio  UNIQUE (nombre, anio),
  CONSTRAINT ck_temp_nivel        CHECK (nivel IN ('ALTA','MEDIA','BAJA')),
  CONSTRAINT ck_temp_anio         CHECK (anio BETWEEN 2000 AND 2100),
  CONSTRAINT ck_temp_anio_inicio  CHECK (anio = EXTRACT(YEAR FROM fecha_inicio)),
  CONSTRAINT ck_temp_fechas       CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_temp_sin_hora     CHECK (fecha_inicio = TRUNC(fecha_inicio)
                                     AND fecha_fin    = TRUNC(fecha_fin))
);

/* -----------------------------------------------------------------------------
   TARIFA
   Precio por noche de UNA habitación en UNA temporada (resuelve la "primera
   decisión de diseño": una estadía que cruza temporadas se valora noche a
   noche buscando, para cada noche, la temporada que contiene esa fecha y la
   tarifa de la habitación en ella). No es un porcentaje sobre un precio base.
   - UNIQUE(id_habitacion, id_temporada): una sola tarifa por combinación.
   - Se carga derivándola del cruce HABITACION x TEMPORADA, no digitada suelta.
   ----------------------------------------------------------------------------- */
CREATE TABLE tarifa (
  id_tarifa      NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_habitacion  NUMBER(10)     NOT NULL,
  id_temporada   NUMBER(10)     NOT NULL,
  precio_noche   NUMBER(10,2)   NOT NULL,
  CONSTRAINT pk_tarifa           PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_tarifa_hab       FOREIGN KEY (id_habitacion) REFERENCES habitacion (id_habitacion),
  CONSTRAINT fk_tarifa_temp      FOREIGN KEY (id_temporada)  REFERENCES temporada (id_temporada),
  CONSTRAINT uq_tarifa_hab_temp  UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_precio    CHECK (precio_noche > 0)
);

/* =============================================================================
   4. CLIENTES Y RESERVAS
   ============================================================================= */

/* -----------------------------------------------------------------------------
   CLIENTE
   Persona que reserva. Un cliente tiene muchas reservas en el tiempo.
   - UNIQUE(tipo_documento, numero_documento): el número solo identifica en
     combinación con el tipo (un pasaporte puede coincidir con una cédula).
   - UNIQUE(correo): un correo, un cliente.
   - ciudad_origen: texto libre (hay clientes de fuera del Quindío).
   ----------------------------------------------------------------------------- */
CREATE TABLE cliente (
  id_cliente        NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_documento    VARCHAR2(3)         NOT NULL,
  numero_documento  VARCHAR2(20)        NOT NULL,
  nombre            VARCHAR2(80 CHAR)   NOT NULL,
  apellido          VARCHAR2(80 CHAR)   NOT NULL,
  correo            VARCHAR2(120)       NOT NULL,
  telefono          VARCHAR2(20)        NOT NULL,
  ciudad_origen     VARCHAR2(80 CHAR)   NOT NULL,
  fecha_registro    DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_cliente         PRIMARY KEY (id_cliente),
  CONSTRAINT uq_cliente_doc     UNIQUE (tipo_documento, numero_documento),
  CONSTRAINT uq_cliente_correo  UNIQUE (correo),
  CONSTRAINT ck_cliente_tipodoc CHECK (tipo_documento IN ('CC','CE','TI','PAS')),
  CONSTRAINT ck_cliente_correo  CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
  CONSTRAINT ck_cliente_tel     CHECK (REGEXP_LIKE(telefono, '^[0-9 +().-]{7,20}$'))
);

/* -----------------------------------------------------------------------------
   RESERVA
   Cabecera de la reserva: quién, en qué alojamiento, rango general de fechas
   y estado. El detalle (qué habitaciones) vive en RESERVA_HABITACION.
   - id_alojamiento: se guarda aquí porque una reserva es siempre de UN solo
     alojamiento (varias habitaciones del mismo sitio). Con las FK compuestas
     de las tablas hijas, el motor garantiza que habitaciones, servicios y
     reseña de una reserva pertenezcan a ese mismo alojamiento.
   - UNIQUE(id_reserva, id_alojamiento): destino de esas FK compuestas.
   - fecha_cancelacion: necesaria para la regla de reembolso (más de 5 días de
     anticipación al check-in = 80 %, menos = 0 %). CHECK: solo las reservas
     CANCELADA la tienen, y todas las CANCELADA la tienen.
   - El valor total NO se almacena: se calcula con fn_valor_estadia (estadía)
     + servicios, para no duplicar un dato derivable (3FN).
   ----------------------------------------------------------------------------- */
CREATE TABLE reserva (
  id_reserva         NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_cliente         NUMBER(10)    NOT NULL,
  id_alojamiento     NUMBER(10)    NOT NULL,
  fecha_checkin      DATE          NOT NULL,
  fecha_checkout     DATE          NOT NULL,
  estado             VARCHAR2(10)  DEFAULT 'PENDIENTE' NOT NULL,
  fecha_creacion     DATE          DEFAULT SYSDATE NOT NULL,
  fecha_cancelacion  DATE,                               -- solo si estado = CANCELADA
  CONSTRAINT pk_reserva           PRIMARY KEY (id_reserva),
  CONSTRAINT fk_reserva_cliente   FOREIGN KEY (id_cliente)     REFERENCES cliente (id_cliente),
  CONSTRAINT fk_reserva_aloj      FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_reserva_id_aloj   UNIQUE (id_reserva, id_alojamiento),
  CONSTRAINT ck_reserva_estado    CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
  CONSTRAINT ck_reserva_fechas    CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reserva_sin_hora  CHECK (fecha_checkin  = TRUNC(fecha_checkin)
                                     AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reserva_cancel    CHECK (
        (estado  = 'CANCELADA' AND fecha_cancelacion IS NOT NULL)
     OR (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL))
);

/* -----------------------------------------------------------------------------
   RESERVA_HABITACION  (tabla de detalle: resuelve la "segunda decisión de
   diseño": una reserva toma varias habitaciones)
   Una fila = una habitación dentro de una reserva, con SUS fechas (pueden ser
   un rango menor al de la cabecera: alguien llega un día después) y el número
   de huéspedes alojados.
   - FK compuesta (id_reserva, id_alojamiento) -> RESERVA: la línea hereda el
     alojamiento de la cabecera.
   - FK compuesta (id_habitacion, id_alojamiento) -> HABITACION: la habitación
     debe ser de ESE alojamiento. Así es imposible mezclar alojamientos.
   - UNIQUE(id_reserva, id_habitacion): una habitación aparece una vez por reserva.
   - LIMITACIONES (se validan en la Entrega 2, no se pueden declarar aquí):
       * que las fechas de la línea queden dentro del rango de la cabecera;
       * que num_huespedes <= HABITACION.capacidad;
       * que la habitación no esté ocupada por otra reserva confirmada en el
         rango (disparador de solape + sp_crear_reserva).
   ----------------------------------------------------------------------------- */
CREATE TABLE reserva_habitacion (
  id_reserva_hab  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva      NUMBER(10)    NOT NULL,
  id_habitacion   NUMBER(10)    NOT NULL,
  id_alojamiento  NUMBER(10)    NOT NULL,
  fecha_checkin   DATE          NOT NULL,
  fecha_checkout  DATE          NOT NULL,
  num_huespedes   NUMBER(2)     NOT NULL,
  CONSTRAINT pk_reserva_hab        PRIMARY KEY (id_reserva_hab),
  CONSTRAINT fk_rh_reserva         FOREIGN KEY (id_reserva, id_alojamiento)
                                   REFERENCES reserva (id_reserva, id_alojamiento),
  CONSTRAINT fk_rh_habitacion      FOREIGN KEY (id_habitacion, id_alojamiento)
                                   REFERENCES habitacion (id_habitacion, id_alojamiento),
  CONSTRAINT uq_rh_reserva_hab     UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_rh_fechas          CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_rh_sin_hora        CHECK (fecha_checkin  = TRUNC(fecha_checkin)
                                      AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_rh_huespedes       CHECK (num_huespedes >= 1)
);

/* =============================================================================
   5. PAGOS Y SERVICIOS COMPLEMENTARIOS
   ============================================================================= */

/* -----------------------------------------------------------------------------
   PAGO
   Abono o pago de una reserva (una reserva puede tener varios: anticipo +
   saldo). Una reserva se considera pagada cuando la suma de sus pagos
   EXITOSO cubre estadía + servicios (se calcula, no se guarda).
   - monto siempre positivo; un reembolso se representa con estado
     REEMBOLSADO, no con monto negativo.
   ----------------------------------------------------------------------------- */
CREATE TABLE pago (
  id_pago      NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva   NUMBER(10)     NOT NULL,
  fecha_pago   DATE           DEFAULT SYSDATE NOT NULL,
  monto        NUMBER(12,2)   NOT NULL,
  metodo       VARCHAR2(16)   NOT NULL,
  estado       VARCHAR2(11)   DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT pk_pago          PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_reserva  FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
  CONSTRAINT ck_pago_monto    CHECK (monto > 0),
  CONSTRAINT ck_pago_metodo   CHECK (metodo IN ('TARJETA_CREDITO','TARJETA_DEBITO',
                                                'PSE','TRANSFERENCIA','EFECTIVO')),
  CONSTRAINT ck_pago_estado   CHECK (estado IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO'))
);

/* -----------------------------------------------------------------------------
   SERVICIO
   Servicio adicional que ofrece UN alojamiento (desayuno, tour, spa...). El
   "desayuno" del Hotel X y el del Hotel Y son filas distintas.
   - UNIQUE(id_alojamiento, nombre): no se repite un servicio dentro del mismo
     alojamiento.
   - UNIQUE(id_servicio, id_alojamiento): destino de la FK compuesta de
     RESERVA_SERVICIO.
   - precio >= 0 (se permite 0 para servicios cortesía).
   ----------------------------------------------------------------------------- */
CREATE TABLE servicio (
  id_servicio     NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento  NUMBER(10)          NOT NULL,
  nombre          VARCHAR2(80 CHAR)   NOT NULL,
  descripcion     VARCHAR2(300 CHAR),                    -- opcional
  precio          NUMBER(10,2)        NOT NULL,
  CONSTRAINT pk_servicio          PRIMARY KEY (id_servicio),
  CONSTRAINT fk_serv_alojamiento  FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_serv_aloj_nombre  UNIQUE (id_alojamiento, nombre),
  CONSTRAINT uq_serv_id_aloj      UNIQUE (id_servicio, id_alojamiento),
  CONSTRAINT ck_serv_precio       CHECK (precio >= 0)
);

/* -----------------------------------------------------------------------------
   RESERVA_SERVICIO  (tabla asociativa N:M entre RESERVA y SERVICIO)
   Servicios contratados dentro de una reserva, con cantidad (p. ej. 2 tours).
   - PK compuesta (id_reserva, id_servicio): un servicio aparece una vez por
     reserva; para más unidades se sube cantidad.
   - precio_unitario: copia del precio vigente al contratar, para que un
     cambio posterior en SERVICIO.precio no altere reservas ya hechas.
   - FK compuestas: el servicio debe ser del mismo alojamiento que la reserva.
   ----------------------------------------------------------------------------- */
CREATE TABLE reserva_servicio (
  id_reserva       NUMBER(10)     NOT NULL,
  id_servicio      NUMBER(10)     NOT NULL,
  id_alojamiento   NUMBER(10)     NOT NULL,
  cantidad         NUMBER(3)      NOT NULL,
  precio_unitario  NUMBER(10,2)   NOT NULL,
  CONSTRAINT pk_reserva_servicio  PRIMARY KEY (id_reserva, id_servicio),
  CONSTRAINT fk_rs_reserva        FOREIGN KEY (id_reserva, id_alojamiento)
                                  REFERENCES reserva (id_reserva, id_alojamiento),
  CONSTRAINT fk_rs_servicio       FOREIGN KEY (id_servicio, id_alojamiento)
                                  REFERENCES servicio (id_servicio, id_alojamiento),
  CONSTRAINT ck_rs_cantidad       CHECK (cantidad >= 1),
  CONSTRAINT ck_rs_precio         CHECK (precio_unitario >= 0)
);

/* =============================================================================
   6. RESEÑAS Y USUARIOS INTERNOS
   ============================================================================= */

/* -----------------------------------------------------------------------------
   RESENA
   Reseña de un alojamiento ligada a la reserva con que se hospedó el cliente.
   - UNIQUE(id_reserva): máximo una reseña por reserva.
   - FK compuesta (id_reserva, id_alojamiento): la reseña es del alojamiento
     de esa reserva; el cliente se obtiene por RESERVA (no se duplica).
   - calificacion de 1 a 5; comentario opcional.
   - LIMITACIÓN: que la reserva esté en estado COMPLETADA no se puede validar
     con un CHECK (el estado está en otra tabla). Se valida con un disparador
     o en el procedimiento de inserción (Entrega 2).
   ----------------------------------------------------------------------------- */
CREATE TABLE resena (
  id_resena       NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva      NUMBER(10)           NOT NULL,
  id_alojamiento  NUMBER(10)           NOT NULL,
  calificacion    NUMBER(1)            NOT NULL,
  comentario      VARCHAR2(1000 CHAR),                   -- opcional
  fecha_resena    DATE                 DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_resena          PRIMARY KEY (id_resena),
  CONSTRAINT fk_resena_reserva  FOREIGN KEY (id_reserva, id_alojamiento)
                                REFERENCES reserva (id_reserva, id_alojamiento),
  CONSTRAINT uq_resena_reserva  UNIQUE (id_reserva),
  CONSTRAINT ck_resena_calif    CHECK (calificacion BETWEEN 1 AND 5)
);

/* -----------------------------------------------------------------------------
   USUARIO_SISTEMA
   Usuarios internos de la plataforma. El rol define qué puede hacer y se
   conecta con los roles de base de datos de la Entrega 3 (recepción,
   administrador de alojamiento, gerente, auditor).
   - id_alojamiento: el alojamiento que gestiona (NULL para quienes no
     pertenecen a uno). CHECK: un ENCARGADO siempre tiene alojamiento y un
     ADMIN_PLATAFORMA nunca.
   - UNIQUE(nombre_usuario) y UNIQUE(correo).
   ----------------------------------------------------------------------------- */
CREATE TABLE usuario_sistema (
  id_usuario       NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre_usuario   VARCHAR2(30)        NOT NULL,
  nombre_completo  VARCHAR2(120 CHAR)  NOT NULL,
  correo           VARCHAR2(120)       NOT NULL,
  rol              VARCHAR2(16)        NOT NULL,
  id_alojamiento   NUMBER(10),                            -- solo encargados / recepción
  estado           VARCHAR2(8)         DEFAULT 'ACTIVO' NOT NULL,
  fecha_creacion   DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_usuario_sistema  PRIMARY KEY (id_usuario),
  CONSTRAINT fk_usr_alojamiento  FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_usr_nombre       UNIQUE (nombre_usuario),
  CONSTRAINT uq_usr_correo       UNIQUE (correo),
  CONSTRAINT ck_usr_rol          CHECK (rol IN ('ADMIN_PLATAFORMA','ENCARGADO','RECEPCION',
                                                'GERENTE','AUDITOR')),
  CONSTRAINT ck_usr_estado       CHECK (estado IN ('ACTIVO','INACTIVO')),
  CONSTRAINT ck_usr_correo       CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
  CONSTRAINT ck_usr_rol_aloj     CHECK (
        (rol = 'ENCARGADO'        AND id_alojamiento IS NOT NULL)
     OR (rol = 'ADMIN_PLATAFORMA' AND id_alojamiento IS NULL)
     OR  rol IN ('RECEPCION','GERENTE','AUDITOR'))
);

/* =============================================================================
   7. COMENTARIOS EN EL DICCIONARIO DE DATOS
   Consultables en USER_TAB_COMMENTS / USER_COL_COMMENTS.
   ============================================================================= */
COMMENT ON TABLE municipio          IS 'Los 12 municipios del Quindio; cada alojamiento pertenece a uno.';
COMMENT ON TABLE tipo_alojamiento   IS 'Catalogo de tipos: finca cafetera, hotel, glamping, hostal y otros.';
COMMENT ON TABLE alojamiento        IS 'Establecimiento turistico con municipio, tipo, contacto y estrellas autoasignadas.';
COMMENT ON TABLE habitacion         IS 'Unidad reservable de un alojamiento; numero unico dentro del alojamiento.';
COMMENT ON TABLE temporada          IS 'Rango de fechas ALTA/MEDIA/BAJA definido por anio (Semana Santa 2025 y 2026 son filas distintas).';
COMMENT ON TABLE tarifa             IS 'Precio por noche de una habitacion en una temporada; base del calculo noche a noche.';
COMMENT ON TABLE cliente            IS 'Persona que reserva; identificada por tipo y numero de documento.';
COMMENT ON TABLE reserva            IS 'Cabecera de la reserva: cliente, alojamiento, rango general de fechas y estado.';
